import { chromium } from 'playwright';
import fs from 'fs';
const b=await chromium.launch({executablePath:'/usr/bin/google-chrome'});
const p=await b.newPage({viewport:{width:1800,height:1000}});
await p.goto('http://localhost:8765/tools/sim.html');
await p.waitForFunction(()=>window.__SIM||window.__ERR,null,{timeout:120000});
const err=await p.evaluate(()=>window.__ERR); if(err) throw new Error(err);
const sim=await p.evaluate(()=>window.__SIM);
fs.writeFileSync('/workspace/geo-party/data/sim.js','// Generated by tools/sim.html (raster look-alike neighbours)\nwindow.GEO_SIM='+JSON.stringify(sim)+';\n');
await p.screenshot({path:'/workspace/geo-party-build/shapes_sheet.png',fullPage:true});
console.log('flag RO',sim.flag.RO.slice(0,5),'ID',sim.flag.ID.slice(0,5),'IE',sim.flag.IE.slice(0,5),'shape BO',sim.shape.BO.slice(0,5),'KG',sim.shape.KG.slice(0,5));
await b.close();
